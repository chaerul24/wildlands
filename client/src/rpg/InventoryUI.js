import { RPG_ITEMS } from './RPGConfig.js';

export class InventoryUI {
  constructor(inventoryManager, combatRef = null, inputManager = null) {
    this.inventory = inventoryManager;
    this.combat = combatRef;
    this.input = inputManager;

    this.isOpen = false;
    this.selectedItemId = null;

    this.modalEl = null;
    this.createDOM();
  }

  createDOM() {
    this.modalEl = document.createElement('div');
    this.modalEl.id = 'rpg-inventory-modal';
    this.modalEl.className = 'rpg-inventory-overlay';
    this.modalEl.style.display = 'none';

    this.modalEl.innerHTML = `
      <div class="rpg-inventory-card">
        <header class="inventory-header">
          <div class="inventory-title-group">
            <span style="font-size: 24px;">🎒</span>
            <h2 class="inventory-title">TAS PETUALANG & PERLENGKAPAN</h2>
          </div>
          <button id="btn-close-inv" class="dialogue-close-btn" type="button" aria-label="Tutup Inventaris">✕</button>
        </header>

        <div class="inventory-content-grid">
          <!-- 1. Left: Character Equipment & Stats -->
          <div class="character-equip-col">
            <h3 style="font-size: 13px; font-weight: 800; color: #94a3b8; text-transform: uppercase; letter-spacing: 0.5px;">PERLENGKAPAN AKTIF</h3>

            <div class="equip-slots-group">
              <!-- Weapon -->
              <div class="equip-slot-item" id="slot-weapon">
                <div class="slot-icon-box" id="icon-slot-weapon">🗡️</div>
                <div class="slot-details">
                  <span class="slot-label">SENJATA UTAMA</span>
                  <span class="slot-item-name" id="name-slot-weapon">Pedang Kayu</span>
                </div>
                <button class="btn-unequip" data-slot="weapon" type="button">Lepas</button>
              </div>

              <!-- Shield / Offhand -->
              <div class="equip-slot-item" id="slot-shield">
                <div class="slot-icon-box" id="icon-slot-shield">🛡️</div>
                <div class="slot-details">
                  <span class="slot-label">OFF-HAND / PERISAI</span>
                  <span class="slot-item-name" id="name-slot-shield">Perisai Kayu</span>
                </div>
                <button class="btn-unequip" data-slot="shield" type="button">Lepas</button>
              </div>

              <!-- Armor -->
              <div class="equip-slot-item" id="slot-armor">
                <div class="slot-icon-box" id="icon-slot-armor">🥋</div>
                <div class="slot-details">
                  <span class="slot-label">ZIRAH BADAN</span>
                  <span class="slot-item-name" id="name-slot-armor">Rompi Kulit</span>
                </div>
                <button class="btn-unequip" data-slot="armor" type="button">Lepas</button>
              </div>
            </div>

            <!-- Stats -->
            <div class="character-stats-box">
              <h3 style="font-size: 11px; font-weight: 800; color: #f59e0b; text-transform: uppercase;">ATRIBUT KARAKTER</h3>
              <div class="stat-row"><span>Tingkat (Level)</span><strong id="stat-level">Lv. 1</strong></div>
              <div class="stat-row"><span>Health Maksimal</span><strong id="stat-hp">100 HP</strong></div>
              <div class="stat-row"><span>Stamina Maksimal</span><strong id="stat-sta">100 STA</strong></div>
              <div class="stat-row"><span>Kekuatan Serang (ATK)</span><strong id="stat-atk" style="color: #f87171;">20 ATK</strong></div>
              <div class="stat-row"><span>Pertahanan (DEF)</span><strong id="stat-def" style="color: #60a5fa;">6 DEF</strong></div>
              <div class="stat-row"><span>Peluang Kritikal</span><strong id="stat-crit">5%</strong></div>
            </div>
          </div>

          <!-- 2. Right: Bag Slots & Item Preview -->
          <div class="inventory-bag-col">
            <div class="bag-grid-header">
              <span>KAPASITAS TAS (16 SLOT)</span>
              <span id="bag-count-text">2/16 Terisi</span>
            </div>

            <div class="bag-grid-container" id="bag-slots-grid">
              <!-- 16 slots generated by JS -->
            </div>

            <!-- Bottom Item Inspector Panel -->
            <div class="item-preview-card" id="item-inspector-card" style="display: none;">
              <div class="item-preview-info">
                <span class="preview-name" id="inspector-name">Nama Item</span>
                <span class="preview-desc" id="inspector-desc">Deskripsi item akan ditampilkan di sini.</span>
              </div>
              <div class="preview-actions" id="inspector-actions">
                <button class="btn-item-action use" id="btn-inspector-action" type="button">Gunakan</button>
              </div>
            </div>
          </div>
        </div>
      </div>
    `;
    document.body.appendChild(this.modalEl);

    // Close button
    const btnClose = this.modalEl.querySelector('#btn-close-inv');
    if (btnClose) {
      btnClose.addEventListener('click', () => this.close());
    }

    // Click outside to close
    this.modalEl.addEventListener('click', (e) => {
      if (e.target === this.modalEl) {
        this.close();
      }
    });

    // Unequip buttons
    this.modalEl.querySelectorAll('.btn-unequip').forEach(btn => {
      btn.addEventListener('click', (e) => {
        const slot = e.target.getAttribute('data-slot');
        if (slot) {
          this.inventory.unequipItem(slot);
          this.render();
        }
      });
    });
  }

  toggle() {
    if (this.isOpen) {
      this.close();
    } else {
      this.open();
    }
  }

  open() {
    this.isOpen = true;
    if (this.input) {
      this.input.exitPointerLock();
    }
    this.render();
    this.modalEl.style.display = 'flex';
  }

  close() {
    this.isOpen = false;
    this.selectedItemId = null;
    if (this.modalEl) {
      this.modalEl.style.display = 'none';
    }
    if (this.input) {
      this.input.requestPointerLock();
    }
  }

  render() {
    if (!this.modalEl) return;

    const stats = this.inventory.getStats();

    // 1. Render Stats
    const statLevel = this.modalEl.querySelector('#stat-level');
    const statHp = this.modalEl.querySelector('#stat-hp');
    const statSta = this.modalEl.querySelector('#stat-sta');
    const statAtk = this.modalEl.querySelector('#stat-atk');
    const statDef = this.modalEl.querySelector('#stat-def');
    const statCrit = this.modalEl.querySelector('#stat-crit');

    if (statLevel) statLevel.textContent = `Lv. ${stats.level}`;
    if (statHp) statHp.textContent = `${stats.maxHp} HP`;
    if (statSta) statSta.textContent = `${stats.maxStamina} STA`;
    if (statAtk) statAtk.textContent = `${stats.attack} ATK`;
    if (statDef) statDef.textContent = `${stats.defense} DEF`;
    if (statCrit) statCrit.textContent = `${Math.round(stats.critChance * 100)}%`;

    // 2. Render Equipment Slots
    const slots = ['weapon', 'shield', 'armor'];
    for (const slot of slots) {
      const eqId = this.inventory.equipped[slot];
      const itemDef = eqId ? RPG_ITEMS[eqId] : null;
      const iconEl = this.modalEl.querySelector(`#icon-slot-${slot}`);
      const nameEl = this.modalEl.querySelector(`#name-slot-${slot}`);

      if (itemDef) {
        if (iconEl) iconEl.textContent = itemDef.icon || '⚔️';
        if (nameEl) nameEl.textContent = itemDef.name;
      } else {
        if (iconEl) iconEl.textContent = slot === 'weapon' ? '🗡️' : (slot === 'shield' ? '🛡️' : '🥋');
        if (nameEl) nameEl.textContent = '(Kosong)';
      }
    }

    // 3. Render 16 Bag Slots
    const bagGrid = this.modalEl.querySelector('#bag-slots-grid');
    const bagCountText = this.modalEl.querySelector('#bag-count-text');
    if (bagCountText) {
      bagCountText.textContent = `${this.inventory.items.length}/${this.inventory.maxSlots} Terisi`;
    }

    if (bagGrid) {
      bagGrid.innerHTML = '';
      for (let i = 0; i < this.inventory.maxSlots; i++) {
        const slotData = this.inventory.items[i];
        const slotEl = document.createElement('div');
        slotEl.className = 'bag-slot';

        if (slotData && RPG_ITEMS[slotData.id]) {
          const itemDef = RPG_ITEMS[slotData.id];
          if (this.selectedItemId === itemDef.id) {
            slotEl.classList.add('selected');
          }

          slotEl.innerHTML = `
            <span class="bag-slot-icon">${itemDef.icon || '📦'}</span>
            ${slotData.count > 1 ? `<span class="bag-slot-count">${slotData.count}</span>` : ''}
          `;

          slotEl.onclick = () => {
            this.selectedItemId = itemDef.id;
            this.renderInspector(itemDef);
            this.render();
          };
        } else {
          slotEl.style.opacity = '0.35';
          slotEl.onclick = () => {
            this.selectedItemId = null;
            this.hideInspector();
            this.render();
          };
        }

        bagGrid.appendChild(slotEl);
      }
    }
  }

  renderInspector(itemDef) {
    const card = this.modalEl.querySelector('#item-inspector-card');
    const nameEl = this.modalEl.querySelector('#inspector-name');
    const descEl = this.modalEl.querySelector('#inspector-desc');
    const actionsEl = this.modalEl.querySelector('#inspector-actions');

    if (!card || !itemDef) return;

    card.style.display = 'flex';
    nameEl.textContent = `${itemDef.icon} ${itemDef.name}`;
    descEl.textContent = itemDef.description || '';

    actionsEl.innerHTML = '';

    if (itemDef.type === 'consumable') {
      const btnUse = document.createElement('button');
      btnUse.className = 'btn-item-action use';
      btnUse.textContent = 'Gunakan (Use)';
      btnUse.onclick = () => {
        this.inventory.useItem(itemDef.id, this.combat);
        this.render();
      };
      actionsEl.appendChild(btnUse);
    } else if (['weapon', 'shield', 'armor'].includes(itemDef.type)) {
      const btnEquip = document.createElement('button');
      btnEquip.className = 'btn-item-action equip';
      btnEquip.textContent = 'Pasang (Equip)';
      btnEquip.onclick = () => {
        this.inventory.equipItem(itemDef.id);
        this.render();
      };
      actionsEl.appendChild(btnEquip);
    }
  }

  hideInspector() {
    const card = this.modalEl.querySelector('#item-inspector-card');
    if (card) card.style.display = 'none';
  }
}
